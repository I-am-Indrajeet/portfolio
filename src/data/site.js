export function normalizePath(path = "/") {
  const clean = path.split("?")[0].split("#")[0];
  return clean === "/" || clean.endsWith(".html")
    ? clean
    : clean.replace(/\/+$/, "") + "/";
}
export function getPage(path) {
  return pages.find((p) => p.path === normalizePath(path)) || pages.at(-1);
}
